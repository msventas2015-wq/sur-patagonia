const luminance=hex=>{const rgb=hex.replace('#','').match(/../g).map(x=>parseInt(x,16)/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4);return .2126*rgb[0]+.7152*rgb[1]+.0722*rgb[2]};
export const contrast=(a,b)=>(Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05);
export function paletteTokens(id){
 const p=MINIWEB_PALETTES.find(p=>p.id===id)||MINIWEB_PALETTES[0],v={...p};
 v.secondaryFondo=contrast(p.texto2,p.fondo)>=4.5?p.texto2:p.texto;
 v.secondarySuperficie=contrast(p.texto2,p.superficie)>=4.5?p.texto2:p.texto;
 v.actionBg=contrast(p.accion,p.textoAccion)>=4.5?p.accion:p.oscuro;
 v.actionFg=contrast(p.accion,p.textoAccion)>=4.5?p.textoAccion:p.textoInverso;
 v.logoFilter=luminance(p.fondo)>.45?'brightness(0)':'brightness(0) invert(1)';
 v.logoSurfaceFilter=luminance(p.superficie)>.45?'brightness(0)':'brightness(0) invert(1)';
 return v;
}
export function applyMiniwebPalette(element,id){const p=paletteTokens(id);for(const [key,value]of Object.entries(p))if(typeof value==='string'&&/^#[0-9a-f]{6}$/i.test(value))element.style.setProperty('--pal-'+key,value);element.style.setProperty('--logo-filter',p.logoFilter);element.style.setProperty('--logo-surface-filter',p.logoSurfaceFilter);element.dataset.palette=p.id;}
